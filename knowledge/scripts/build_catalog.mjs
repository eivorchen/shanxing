import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {CONFIG as baseConfig, SOURCES as baseSources, SERVICES} from '../base-data.js';
import {SOURCES as lastPublished} from '../../data.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const collected = JSON.parse(await fs.readFile(path.join(root, 'outputs/collected.json'),'utf8'));
const reviews = JSON.parse(await fs.readFile(path.join(root, 'review.json'),'utf8'));
const sites = JSON.parse(await fs.readFile(path.join(root, 'sites.json'),'utf8'));
const prior = JSON.parse(await fs.readFile(path.join(root,'base-imported-urls.json'),'utf8'));
const ledger=JSON.parse(await fs.readFile(path.join(root,'import-ledger.json'),'utf8').catch(()=>'{"documents":[]}'));
const existing = new Set([...prior,...ledger.documents.filter(d=>d.status==='imported').map(d=>d.url)]);
const approved = [], rejected=[];
const seenUrls = new Set(), seenBodies = new Set();
for (const item of collected) {
  const review = reviews[item.id];
  if (!review?.approved) {rejected.push({id:item.id,url:item.url,reason:review?.reason||'尚未核验，不自动发布'});continue;}
  const source = {...item,...review,status:'verified'};
  delete source.approved;
  const site=sites.find(s=>s.id===item.site_id);
  if (!site.hosts.includes(new URL(source.url).hostname)) throw Error(`Unapproved host: ${source.id}`);
  if (seenUrls.has(source.url) || seenBodies.has(source.content_sha256)) throw Error(`Duplicate: ${source.id}`);
  if (!source.title || !source.summary || !source.text || source.http_status!==200) throw Error(`Incomplete: ${source.id}`);
  if(review.reviewed_content_sha256 && review.reviewed_content_sha256!==item.content_sha256) {
    rejected.push({id:item.id,url:item.url,reason:'正文变化，等待复核摘要与适用范围'});continue;
  }
  source.aliases=source.aliases.filter(alias=>(source.title+source.text).includes(alias));
  source.verified=source.fetched_at.slice(0,10);
  source.published ||= '页面未标注发布日期';
  source.types ||= [source.type];
  source.import_state=existing.has(source.url)?'existing':'ready';
  source.filename=`${source.mountain}_${source.id}_${source.verified.replaceAll('-','')}.md`;
  seenUrls.add(source.url);seenBodies.add(source.content_sha256);approved.push(source);
}
await fs.mkdir(path.join(root,'docs'),{recursive:true});
for (const source of approved) {
  const body=`# ${source.title}\n\n山岳或景区：${source.mountain}\n资料类别：${source.types.join('、')}\n发布机构：${source.issuer}\n原文网址：${source.url}\n发布日期：${source.published}\n采集核验日期：${source.verified}\n${source.scope?'适用范围：'+source.scope+'\n':''}${source.validUntil?'适用截止日：'+source.validUntil+'\n':''}\n## 资料摘要\n\n${source.summary}\n\n## 官方正文\n\n${source.text}\n`;
  await fs.writeFile(path.join(root,'docs',source.filename),body);
}
const baseUrls=new Set(baseSources.map(s=>s.url));
const frontend=[...baseSources,...lastPublished.filter(s=>!baseUrls.has(s.url)&&reviews[s.id]?.approved!==false)];
for (const source of approved) {
  if(baseUrls.has(source.url))continue;
  const {id,mountain,aliases,type,types,title,issuer,published,url,summary,verified,event,kind,scope}=source;
  const entry={id,mountain,aliases,type,types,title,issuer,published,url,summary,verified,...(event?{event}:{}),...(kind?{kind}:{}),...(scope?{scope}:{})};
  const index=frontend.findIndex(s=>s.url===source.url);if(index<0)frontend.push(entry);else frontend[index]=entry;
}
const mountains=[...new Set(frontend.map(s=>s.mountain).filter(x=>!['全国','四川山峰'].includes(x)))];
const config={...baseConfig,verified:approved.map(s=>s.verified).sort().at(-1),sourceCount:frontend.length,mountainCount:mountains.length};
const text=`// Generated by knowledge/scripts/build_catalog.mjs. Edit knowledge/review.json.\nexport const CONFIG = ${JSON.stringify(config,null,2)};\nexport const SOURCES = ${JSON.stringify(frontend,null,2)};\nexport const SERVICES = ${JSON.stringify(SERVICES,null,2)};\nexport const MOUNTAINS = ${JSON.stringify(mountains)};\n`;
await fs.writeFile(path.resolve(root,'../data.js'),text);
await fs.writeFile(path.join(root,'outputs/approved.json'),JSON.stringify(approved,null,2));
await fs.writeFile(path.join(root,'outputs/rejected.json'),JSON.stringify(rejected,null,2));
await fs.writeFile(path.join(root,'outputs/import-urls.json'),JSON.stringify(approved.filter(s=>!existing.has(s.url)).map(s=>s.url),null,2));
const counts={};for(const s of approved)counts[s.mountain]=(counts[s.mountain]||0)+1;
const manifest={built_at:new Date().toISOString(),approved:approved.length,rejected:rejected.length,ready_for_import:approved.filter(s=>!existing.has(s.url)).length,frontend_sources:frontend.length,mountains,by_mountain:counts,content_manifest_sha256:crypto.createHash('sha256').update(JSON.stringify(approved.map(s=>[s.id,s.content_sha256]))).digest('hex'),import_status:ledger.documents.length?ledger.status:'not_submitted'};
await fs.writeFile(path.join(root,'outputs/manifest.json'),JSON.stringify(manifest,null,2));
console.log(JSON.stringify(manifest,null,2));
